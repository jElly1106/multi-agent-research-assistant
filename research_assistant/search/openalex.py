"""OpenAlex's official works search, with source-grounded abstract recovery.

The API returns an inverted index, not prose generated by a language model.
Only complete, unambiguous positions are reassembled. External publication
locations are evidence for downstream readers; this adapter never fetches them.
"""
from __future__ import annotations

import json
from pathlib import Path
import re
from urllib.parse import urlencode, urlsplit

from ..schemas import Paper
from .models import ProviderError, ProviderResult, SearchHit
from .providers import _arxiv_id, _doi, _evidence, _finish, _text, _validate_query
from .transport import HttpTransport


_WORK_ID = re.compile(r"https://openalex\.org/(W[1-9]\d*)\Z")
# OpenAlex has both legacy and current conference-paper labels. Exclude
# datasets, software, editorials, corrections and non-research objects.
_PAPER_TYPES = frozenset({
    "article", "review", "preprint", "conference-paper", "proceedings-article",
    "book-chapter", "book", "dissertation", "report",
})
_MAX_ABSTRACT_WORDS = 100_000


def _abstract(index) -> tuple[str, str]:
    """Return the authentic complete abstract, or empty text plus a reason."""
    if index is None or index == {}:
        return "", "未提供摘要"
    if not isinstance(index, dict):
        return "", "摘要倒排索引不是对象"
    positions: dict[int, str] = {}
    for word, offsets in index.items():
        if not isinstance(word, str) or not word.strip() or not isinstance(offsets, list) or not offsets:
            return "", "摘要倒排索引包含无效词或位置列表"
        for position in offsets:
            if isinstance(position, bool) or not isinstance(position, int) or not 0 <= position < _MAX_ABSTRACT_WORDS:
                return "", "摘要倒排索引包含无效或超限位置"
            if position in positions:
                return "", "摘要倒排索引存在重复位置"
            positions[position] = word
    if not positions or len(positions) != max(positions) + 1:
        return "", "摘要倒排索引存在缺口，未补造缺失文字"
    return _text(" ".join(positions[position] for position in range(len(positions)))), ""


def _public_url(value) -> str:
    """Keep public HTTP(S) metadata URLs, without ever following them."""
    value = _text(value)
    if not value or len(value) > 4000 or any(ord(char) < 32 for char in value):
        return ""
    try:
        parsed = urlsplit(value)
        if parsed.scheme not in {"http", "https"} or not parsed.hostname or parsed.username is not None or parsed.password is not None:
            return ""
        if parsed.port not in {None, 80, 443}:
            return ""
        # Never expose local or reserved pseudo-host locations as reader URLs.
        host = parsed.hostname.lower()
        if host in {"localhost", "localhost.localdomain"} or host.endswith((".local", ".localhost")):
            return ""
        import ipaddress
        try:
            if not ipaddress.ip_address(host).is_global:
                return ""
        except ValueError:
            if "." not in host:
                return ""
        return value
    except ValueError:
        return ""


def _arxiv_from_location(value: str) -> str:
    if not value:
        return ""
    parsed = urlsplit(value)
    if parsed.hostname not in {"arxiv.org", "www.arxiv.org"} or parsed.query or parsed.fragment:
        return ""
    for prefix in ("/abs/", "/pdf/"):
        if parsed.path.startswith(prefix):
            return _arxiv_id(parsed.path[len(prefix):].removesuffix(".pdf"))
    return ""


class OpenAlexProvider:
    """Search works without credentials; requests use the shared HTTP policy.

    No API key is read or added to query URLs. Authenticated OpenAlex access
    requires a separately verified, credential-safe transport integration.
    """

    name = "openalex"
    endpoint = "https://api.openalex.org/works"

    def __init__(self, transport=None, *, timeout: float = 20.0, max_retries: int = 2, evidence_dir: str | Path | None = None):
        self.transport = transport if transport is not None else HttpTransport(
            timeout=timeout, max_retries=max_retries, evidence_dir=evidence_dir,
            proxy_mode="auto",
        )

    def search(self, query: str, *, limit: int) -> ProviderResult:
        query = _validate_query(query, limit)
        request_url = self.endpoint + "?" + urlencode({
            "search": query,
            "per-page": limit,
            "select": "id,doi,title,publication_year,authorships,abstract_inverted_index,primary_location,ids,type,primary_topic",
        })
        response = self.transport.get(request_url)
        try:
            payload = json.loads(response.body)
        except (json.JSONDecodeError, UnicodeDecodeError, ValueError):
            raise ProviderError("OpenAlex 返回了无法解析的 JSON 响应。") from None
        if not isinstance(payload, dict) or any(key in payload for key in ("error", "errors", "message")):
            raise ProviderError("OpenAlex 返回了 API 错误或无效的结果对象。")
        data, meta = payload.get("results"), payload.get("meta")
        total = meta.get("count") if isinstance(meta, dict) else None
        if not isinstance(data, list) or isinstance(total, bool) or not isinstance(total, int) or total < 0:
            raise ProviderError("OpenAlex 响应缺少有效的 results/meta.count 字段。")
        if (total == 0 and data) or (total > 0 and not data) or total < len(data):
            raise ProviderError("OpenAlex 响应的 meta.count 与论文条目不一致。")
        hits: list[SearchHit] = []
        warnings: list[str] = []
        for number, item in enumerate(data[:limit], 1):
            if not isinstance(item, dict):
                warnings.append(f"OpenAlex 第 {number} 条记录不是对象，已跳过。")
                continue
            raw_id, title = _text(item.get("id")), _text(item.get("title"))
            matched = _WORK_ID.fullmatch(raw_id)
            if not matched or not title:
                warnings.append(f"OpenAlex 第 {number} 条记录缺少有效的 Work ID 或标题，已跳过。")
                continue
            source_id = matched.group(1)
            publication_type = _text(item.get("type"))
            if publication_type not in _PAPER_TYPES:
                warnings.append(f"OpenAlex {source_id} 的类型 {publication_type or '未知'} 不在学术论文类型中，已跳过。")
                continue
            raw_authors = item.get("authorships")
            if not isinstance(raw_authors, list):
                warnings.append(f"OpenAlex {source_id} 缺少有效的 authorships，已跳过。")
                continue
            authors = []
            author_name_basis = []
            author_name_conflicts = []
            for author_index, authorship in enumerate(raw_authors, 1):
                author = authorship.get("author") if isinstance(authorship, dict) else None
                display_name = _text(author.get("display_name")) if isinstance(author, dict) else ""
                raw_name = _text(authorship.get("raw_author_name")) if isinstance(authorship, dict) else ""
                # A work's original byline is more direct evidence than a
                # merged author profile. Preserve both when they disagree;
                # disagreement alone does not prove either source incorrect.
                name = raw_name or display_name
                if name:
                    authors.append(name)
                    author_name_basis.append({
                        "author_index": author_index,
                        "selected_name": name,
                        "basis": "raw_author_name" if raw_name else "author.display_name",
                    })
                if raw_name and display_name and raw_name != display_name:
                    author_name_conflicts.append({
                        "author_index": author_index,
                        "raw_author_name": raw_name,
                        "display_name": display_name,
                    })
            if not authors or len(authors) != len(raw_authors):
                warnings.append(f"OpenAlex {source_id} 的作者信息不完整，仅保留实际提供的姓名。")
            if author_name_conflicts:
                warnings.append(f"OpenAlex {source_id} 有 {len(author_name_conflicts)} 位作者的文献原始署名与作者档案名不同，采用文献原始署名；差异已保留在证据中，未判定档案名错误。")
            year = item.get("publication_year")
            if year is not None and (isinstance(year, bool) or not isinstance(year, int) or not 1000 <= year <= 9999):
                year = None
                warnings.append(f"OpenAlex {source_id} 的年份无效，保留为未知。")
            abstract, abstract_warning = _abstract(item.get("abstract_inverted_index"))
            if abstract_warning:
                warnings.append(f"OpenAlex {source_id} {abstract_warning}，摘要保留为空。")
            ids = item.get("ids")
            ids = ids if isinstance(ids, dict) else {}
            if ids.get("openalex") is not None and ids["openalex"] != raw_id:
                warnings.append(f"OpenAlex {source_id} 的 ids.openalex 与主标识符冲突，已跳过。")
                continue
            raw_doi = item.get("doi") or ids.get("doi")
            doi = _doi(raw_doi)
            if raw_doi and not doi:
                warnings.append(f"OpenAlex {source_id} 的 DOI 格式无效，已忽略。")
            location = item.get("primary_location")
            location = location if isinstance(location, dict) else {}
            landing = _public_url(location.get("landing_page_url"))
            pdf_url = _public_url(location.get("pdf_url"))
            venue = location.get("source")
            venue = venue if isinstance(venue, dict) else {}
            topic = item.get("primary_topic")
            topic = topic if isinstance(topic, dict) else {}
            field = topic.get("field")
            field = field if isinstance(field, dict) else {}
            arxiv_id = _arxiv_from_location(landing) or _arxiv_from_location(pdf_url)
            if not arxiv_id and doi.startswith("10.48550/arxiv."):
                arxiv_id = _arxiv_id(doi.removeprefix("10.48550/arxiv."))
            evidence = _evidence(response, self.name, source_id)
            evidence.update({
                "doi": doi, "landing_page_url": landing, "pdf_url": pdf_url,
                "publication_type": publication_type,
                "venue": _text(venue.get("display_name")),
                "primary_topic": _text(topic.get("display_name")),
                "field": _text(field.get("display_name")),
                "field_id": _public_url(field.get("id")),
                "author_name_basis": author_name_basis,
                "author_name_conflicts": author_name_conflicts,
            })
            hits.append(SearchHit(
                paper=Paper(title=title, authors=authors, year=year, abstract=abstract, url=f"https://openalex.org/{source_id}", source=self.name),
                source_id=source_id, doi=doi, arxiv_id=arxiv_id, query=query,
                retrieved_at=response.retrieved_at, evidence=evidence,
            ))
        result = _finish(hits, warnings, len(data[:limit]), self.name, response)
        result.response_evidence["total_results"] = total
        return result
